import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const page = read('public/gta6.html');
const script = read('public/gta6.js');
const style = read('public/gta6.css');
const news = read('public/news.html');
const sharedNav = read('public/mobile-final.js');
const admin = read('public/admin-gta6.js');
const sitemap = read('public/sitemap.xml');
assert.match(page, /https:\/\/www\.rockstargames\.com\/VI\//, 'Hub must link to the official GTA VI site');
assert.match(page, /November 19, 2026/, 'Hub must show the official release date');
assert.match(page, /PlayStation 5 · Xbox Series X\|S/, 'Hub must show confirmed launch platforms');
assert.doesNotMatch(page, /rumor|leak/i, 'Hub must not present rumor or leak content');
assert.match(script, /\.from\('gaming_news'\)/, 'Hub must use the existing news feed');
assert.match(script, /\.eq\('enabled', true\)/, 'Hub must request enabled posts only');
assert.match(script, /safeHttpUrl/, 'Hub must validate database-provided URLs');
assert.match(style, /@media\(max-width:760px\)/, 'Hub must include phone layout rules');
assert.match(news, /href="gta6\.html"/, 'News Center must link to the GTA VI hub');
assert.match(sharedNav, /href = 'gta6\.html'/, 'Home navigation must link to the GTA VI hub');
assert.match(admin, /option\.value = 'GTA VI'/, 'Admin must provide a dedicated GTA VI category');
assert.match(sitemap, /https:\/\/markbeen5\.com\/gta6\.html/, 'Sitemap must include the GTA VI hub');
console.log('MB5 GTA VI hub smoke checks passed.');
