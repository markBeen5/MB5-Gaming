import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const legacy = read('public/gta6.html');
const page = read('public/gta6-hub.html');
const news = read('public/news.html');
const sharedNav = read('public/mobile-final.js');
const admin = read('public/admin-gta6.js');
const sitemap = read('public/sitemap.xml');
assert.match(legacy, /gta6-hub\.html/, 'Legacy GTA VI URL must redirect to the current hub');
assert.match(legacy, /noindex,follow/, 'Legacy GTA VI page must stay out of search results');
assert.match(page, /https:\/\/www\.rockstargames\.com\/VI/, 'Current hub must link to the official GTA VI site');
assert.match(page, /NOVEMBER 19, 2026/i, 'Current hub must show the official release date');
assert.match(page, /PlayStation 5|PS5/i, 'Current hub must identify the confirmed PlayStation platform');
assert.match(page, /Xbox Series X\|S/, 'Current hub must identify the confirmed Xbox platform');
assert.match(page, /@media\(max-width:760px\)/, 'Current hub must include phone layout rules');
assert.match(news, /href="gta6-hub\.html"/, 'News Center must link to the current GTA VI hub');
assert.match(sharedNav, /href = 'gta6-hub\.html'/, 'Shared navigation must link to the current GTA VI hub');
assert.match(admin, /option\.value = 'GTA VI'/, 'Admin must provide a dedicated GTA VI category');
assert.match(sitemap, /https:\/\/markbeen5\.com\/gta6-hub\.html/, 'Sitemap must include the current GTA VI hub');
assert.doesNotMatch(sitemap, /https:\/\/markbeen5\.com\/gta6\.html/, 'Sitemap must not advertise the legacy GTA VI URL');
console.log('MB5 GTA VI hub smoke checks passed.');
